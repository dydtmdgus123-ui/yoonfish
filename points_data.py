def today_species(point: dict[str, Any], month: int, limit: int = 4) -> list[str]:
    """해당 월 대상어 3~4종. 월별 테이블을 우선하고, 부족하면 계절 테이블로 보충."""
    monthly = list(point.get("monthly", {}).get(month, []))
    season = season_of(month)
    seasonal = list(point.get("seasonal", {}).get(season, []))
    seen: set[str] = set()
    picked: list[str] = []
    for name in monthly + seasonal:
        if name in seen:
            continue
        seen.add(name)
        picked.append(name)
        if len(picked) >= limit:
            break
    return picked[:limit]
